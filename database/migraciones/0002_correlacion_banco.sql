INSERT INTO rol_permisos (rol_id, permiso_id)
SELECT r.rol_id, p.id
  FROM (VALUES (1), (2)) AS r(rol_id)
  CROSS JOIN permisos p
 WHERE p.codigo IN ('banco.ver', 'banco.registrar')
ON CONFLICT DO NOTHING;
